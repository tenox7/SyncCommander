// FakeBackend synthesizes an arbitrarily large directory tree with no disk or
// network behind it. Every attribute of every entry is derived from a hash of
// its path, so nothing is materialized until a directory is listed and a
// 10M-object tree costs no memory at rest. Two fake backends built with the
// same parameters produce byte-identical trees; the drop/diff knobs skew one
// side against the other. Intended for profiling the scanner, the tree model
// and the UI at scales that are painful to stage on real storage, and as a
// stand-in for a real backend in tests.
//
//	fake://huge                            preset shape
//	fake://x?dirs=8&files=25&depth=5        explicit shape (≈1M objects)
//	fake://x?latency=2ms                    per-List delay, simulates a network backend
//	fake://x?diff=0.1&drop=0.02             10% of files differ, 2% missing on this side
//
// Presets (host component): tiny, small, medium, large, huge, insane.
// Query parameters override the preset.
//
// A file diff= changes differs in one of three ways, a third each: it grew
// (the same first bytes, more of them, a later time), it was rewritten (the
// same size, other bytes, a later time), or only a checksum tells (the same
// size and time, other bytes).
//
// Writes (copy, append, delete, rename, touch) land in an in-memory overlay
// on top of the generated tree, which is not persisted. The fake keeps the
// rules of a real file system (L22): a copy makes the folders it goes into;
// a folder a write made holds only what is written into it, and one made
// again where one was removed starts empty; a renamed folder takes what is
// in it along, and a renamed file its bytes; a path that is not there is an
// error for every call; Remove leaves a folder that holds something; and the
// base is never removed. A copy into it goes through a part file and can be
// resumed, as on a local disk.
//
// Inject makes calls fail, stop half way or wait, by call and by path, so a
// test can reach the retry, resume and cut-off paths.
type FakeBackend struct {
	url       string
	seed      uint64
	dirs      int
	files     int
	depth     int
	maxSize   int64
	vary      bool
	drop      float64
	dropDirs  float64
	diff      float64
	latency   time.Duration
	ckLatency time.Duration
	noData    bool

	mu   sync.RWMutex
	over map[string]map[string]*fakeMut // dir → name → what a write left there

	faults fakeFaults
}

// fakeMut is what a write left at one name: an entry that replaces the
// generated one or adds to its folder, or a tombstone. resolveLocked gives
// the entry at a path in the same form.
type fakeMut struct {
	entry   model.FileEntry
	deleted bool
	// own: a write made it. A folder then holds only what is written into
	// it, never generated children, and a file's bytes are data.
	own  bool
	data []byte
	// gen is the generated path the entry stands for, which a rename keeps:
	// a folder that is not own shows gen's generated children, and a file
	// that is not own holds gen's generated bytes.
	gen string
}

// Distinct salts keep the per-attribute hashes of one path independent.
const (
	fakeSaltShape = 0x9e3779b97f4a7c15
	fakeSaltSize  = 0xbf58476d1ce4e5b9
	fakeSaltTime  = 0x94d049bb133111eb
	fakeSaltDrop  = 0xd6e8feb86659fd93
	fakeSaltDiff  = 0xa0761d6478bd642f
	fakeSaltData  = 0xe7037ed1a0b428db
)

// How diff= changed a generated file.
const (
	fakeSame      = iota
	fakeGrown     // the same first bytes and more, a later time
	fakeRewritten // the same size, other bytes, a later time
	fakeSilent    // the same size and time, other bytes: only a checksum tells
)

var fakeEpoch = time.Date(2020, 1, 1, 0, 0, 0, 0, time.UTC)

var fakePresets = map[string][3]int{
	// name: {dirs per dir, files per dir, depth}
	"tiny":   {3, 10, 2},  // ~140 objects
	"small":  {5, 20, 3},  // ~3.3k
	"medium": {6, 30, 4},  // ~48k
	"large":  {6, 25, 5},  // ~240k
	"huge":   {8, 25, 5},  // ~1M
	"insane": {10, 40, 5}, // ~4.5M
}

func NewFakeBackend(rawURL string) (*FakeBackend, error) {
	u, err := url.Parse(rawURL)
	if err != nil {
		return nil, fmt.Errorf("fake: %v", err)
	}
	shape, ok := fakePresets[u.Host]
	if !ok {
		shape = fakePresets["medium"]
	}
	b := &FakeBackend{
		url:     rawURL,
		seed:    1,
		dirs:    shape[0],
		files:   shape[1],
		depth:   shape[2],
		maxSize: 1 << 20,
		over:    make(map[string]map[string]*fakeMut),
	}
	if err := b.applyQuery(u.Query()); err != nil {
		return nil, err
	}
	dirs, files, approx := b.estimate()
	tilde := ""
	if approx {
		tilde = ">"
	}
	Log.Add("fake", DirIn, fmt.Sprintf("%s: dirs=%d files=%d depth=%d seed=%d → %s%s dirs, %s%s files",
		rawURL, b.dirs, b.files, b.depth, b.seed, tilde, formatCount(dirs), tilde, formatCount(files)))
	return b, nil
}

func (b *FakeBackend) applyQuery(q url.Values) error {
	var errs []string
	num := func(key string, dst any) {
		raw := q.Get(key)
		if raw == "" {
			return
		}
		switch d := dst.(type) {
		case *int:
			v, err := strconv.Atoi(raw)
			if err != nil || v < 0 {
				errs = append(errs, key+"="+raw)
				return
			}
			*d = v
		case *int64:
			v, err := strconv.ParseInt(raw, 10, 64)
			if err != nil || v < 0 {
				errs = append(errs, key+"="+raw)
				return
			}
			*d = v
		case *uint64:
			v, err := strconv.ParseUint(raw, 10, 64)
			if err != nil {
				errs = append(errs, key+"="+raw)
				return
			}
			*d = v
		case *float64:
			v, err := strconv.ParseFloat(raw, 64)
			if err != nil || v < 0 || v > 1 {
				errs = append(errs, key+"="+raw)
				return
			}
			*d = v
		case *time.Duration:
			v, err := time.ParseDuration(raw)
			if err != nil || v < 0 {
				errs = append(errs, key+"="+raw)
				return
			}
			*d = v
		case *bool:
			*d = raw != "0" && raw != "false"
		}
	}
	num("dirs", &b.dirs)
	num("files", &b.files)
	num("depth", &b.depth)
	num("seed", &b.seed)
	num("size", &b.maxSize)
	num("drop", &b.drop)
	num("dropdirs", &b.dropDirs)
	num("diff", &b.diff)
	num("latency", &b.latency)
	num("cklatency", &b.ckLatency)
	num("vary", &b.vary)
	num("nodata", &b.noData)
	if len(errs) > 0 {
		return fmt.Errorf("fake: bad parameter %s", strings.Join(errs, ", "))
	}
	if b.depth > 64 {
		b.depth = 64
	}
	if b.maxSize < 1 {
		b.maxSize = 1
	}
	return nil
}

// estimate returns the object counts the current shape implies. approx is set
// when the count was clamped to keep the multiplication from running away.
func (b *FakeBackend) estimate() (dirs, files int64, approx bool) {
	var level, total int64 = 1, 1
	for k := 1; k <= b.depth; k++ {
		level *= int64(b.dirs)
		total += level
		if total > 1e9 {
			approx = true
			break
		}
	}
	return total - 1, total * int64(b.files), approx
}

func formatCount(n int64) string {
	switch {
	case n >= 1e9:
		return fmt.Sprintf("%.1fB", float64(n)/1e9)
	case n >= 1e6:
		return fmt.Sprintf("%.1fM", float64(n)/1e6)
	case n >= 1e3:
		return fmt.Sprintf("%.1fk", float64(n)/1e3)
	default:
		return strconv.FormatInt(n, 10)
	}
}

func (b *FakeBackend) BasePath() string { return b.url }

func (b *FakeBackend) List(ctx context.Context, relDir string) ([]model.FileEntry, error) {
	hit, err := b.enter(ctx, FakeList, relDir)
	if err != nil {
		return nil, err
	}
	if err := fakeDelay(ctx, b.latency); err != nil {
		return nil, err
	}
	b.mu.RLock()
	defer b.mu.RUnlock()
	n, ok := b.resolveLocked(relDir)
	switch {
	case !ok:
		return nil, fakeMissing(relDir)
	case !n.entry.IsDir:
		return nil, fmt.Errorf("fake: %s is a file, not a folder", relDir)
	}
	return b.listLocked(relDir, n), hit.done(nil)
}

// listLocked is the folder relDir's listing, n its node: its generated
// children, when it has any, with the writes in it over them.
func (b *FakeBackend) listLocked(relDir string, n fakeMut) []model.FileEntry {
	var entries []model.FileEntry
	if !n.own {
		entries = b.genEntries(n.gen)
		if n.gen != relDir {
			for i := range entries {
				entries[i].RelPath = joinRel(relDir, entries[i].Name)
			}
		}
	}
	return b.overlayLocked(relDir, n, entries)
}

// Stat finds relPath one step at a time from the base, never by listing a
// whole folder.
func (b *FakeBackend) Stat(ctx context.Context, relPath string) (model.FileEntry, error) {
	hit, err := b.enter(ctx, FakeStat, relPath)
	if err != nil {
		return model.FileEntry{}, err
	}
	if err := fakeDelay(ctx, b.latency); err != nil {
		return model.FileEntry{}, err
	}
	b.mu.RLock()
	n, ok := b.resolveLocked(relPath)
	b.mu.RUnlock()
	if !ok {
		return model.FileEntry{}, fakeMissing(relPath)
	}
	return n.entry, hit.done(nil)
}

func fakeMissing(relPath string) error {
	return fmt.Errorf("fake: %s: %w", relPath, fs.ErrNotExist)
}

// resolveLocked returns what is at relPath, with b.mu held: what a write
// left there, or the entry the generator makes in a folder that has
// generated children. Each step down from the base is one map lookup and at
// most one generated entry (L22: Stat, Open and Checksum each made the whole
// listing of the file's folder).
func (b *FakeBackend) resolveLocked(relPath string) (fakeMut, bool) {
	if relPath == "" {
		return fakeMut{entry: model.FileEntry{IsDir: true, Mode: os.ModeDir | 0755}}, true
	}
	dir, name := fakeSplit(relPath)
	parent, ok := b.resolveLocked(dir)
	if !ok || !parent.entry.IsDir {
		return fakeMut{}, false
	}
	if m := b.over[dir][name]; m != nil {
		if m.deleted {
			return fakeMut{}, false
		}
		n := *m
		n.entry = m.at(dir, name)
		return n, true
	}
	if parent.own {
		return fakeMut{}, false
	}
	e, ok := b.genEntry(parent.gen, name)
	if !ok {
		return fakeMut{}, false
	}
	e.RelPath = relPath
	return fakeMut{entry: e, gen: joinRel(parent.gen, name)}, true
}

// at is m's entry as the name name in the folder dir.
func (m *fakeMut) at(dir, name string) model.FileEntry {
	e := m.entry
	e.RelPath, e.Name = joinRel(dir, name), name
	return e
}

func fakeSplit(relPath string) (dir, name string) {
	dir = model.DirOf(relPath)
	return dir, strings.TrimPrefix(relPath[len(dir):], "/")
}

// genEntries derives one directory's children from the hash of its path. Dirs
// come first so a listing looks like a real one; both groups are name-sorted by
// construction.
func (b *FakeBackend) genEntries(relDir string) []model.FileEntry {
	nd, nf := b.genCounts(relDir)
	out := make([]model.FileEntry, 0, nd+nf)
	for i := 0; i < nd; i++ {
		if e, ok := b.genDir(relDir, fakeName("d", i, "")); ok {
			out = append(out, e)
		}
	}
	for i := 0; i < nf; i++ {
		if e, ok := b.genFile(relDir, fakeName("f", i, ".dat")); ok {
			out = append(out, e)
		}
	}
	return out
}

// genEntry is the entry the generator makes for name in the generated folder
// relDir, without the rest of the listing; false for a name it never makes
// there.
func (b *FakeBackend) genEntry(relDir, name string) (model.FileEntry, bool) {
	nd, nf := b.genCounts(relDir)
	if i, ok := fakeIndex(name, "d", ""); ok && i < nd {
		return b.genDir(relDir, name)
	}
	if i, ok := fakeIndex(name, "f", ".dat"); ok && i < nf {
		return b.genFile(relDir, name)
	}
	return model.FileEntry{}, false
}

// genCounts is how many folders and files the generator makes in relDir.
func (b *FakeBackend) genCounts(relDir string) (nd, nf int) {
	depth := 0
	if relDir != "" {
		depth = strings.Count(relDir, "/") + 1
	}
	nd, nf = b.dirs, b.files
	if depth >= b.depth {
		nd = 0
	}
	if b.vary {
		h := xxh3.HashStringSeed(relDir, b.seed^fakeSaltShape)
		nd = varyCount(nd, h)
		nf = varyCount(nf, h>>32)
	}
	return nd, nf
}

func (b *FakeBackend) genDir(relDir, name string) (model.FileEntry, bool) {
	rel := joinRel(relDir, name)
	if b.dropDirs > 0 && fakeFrac(b.hash(rel, fakeSaltDrop)) < b.dropDirs {
		return model.FileEntry{}, false
	}
	e := model.FileEntry{RelPath: rel, Name: name, IsDir: true, Mode: os.ModeDir | 0755}
	b.fillTimes(&e, rel)
	return e, true
}

func (b *FakeBackend) genFile(relDir, name string) (model.FileEntry, bool) {
	rel := joinRel(relDir, name)
	if b.drop > 0 && fakeFrac(b.hash(rel, fakeSaltDrop)) < b.drop {
		return model.FileEntry{}, false
	}
	e := model.FileEntry{
		RelPath: rel,
		Name:    name,
		Size:    int64(b.hash(rel, fakeSaltSize) % uint64(b.maxSize)),
		Mode:    0644,
	}
	b.fillTimes(&e, rel)
	h := b.hash(rel, fakeSaltDiff)
	switch b.diffKind(rel) {
	case fakeGrown:
		e.Size += int64(1 + h%4096)
		e.ModTime = e.ModTime.Add(time.Duration(1+h%3600) * time.Second)
	case fakeRewritten:
		e.ModTime = e.ModTime.Add(time.Duration(1+h%3600) * time.Second)
	}
	return e, true
}

// diffKind is how diff= changed the generated file rel.
func (b *FakeBackend) diffKind(rel string) int {
	if b.diff <= 0 {
		return fakeSame
	}
	h := b.hash(rel, fakeSaltDiff)
	if fakeFrac(h) >= b.diff {
		return fakeSame
	}
	// The low bits: fakeFrac reads the high ones.
	return fakeGrown + int(h&0x7ff)%3
}

// dataSeed seeds the bytes of the generated file gen.
func (b *FakeBackend) dataSeed(gen string) uint64 {
	s := b.hash(gen, fakeSaltData)
	if k := b.diffKind(gen); k == fakeRewritten || k == fakeSilent {
		s ^= fakeSaltDiff
	}
	return s
}

func (b *FakeBackend) fillTimes(e *model.FileEntry, rel string) {
	h := b.hash(rel, fakeSaltTime)
	e.ModTime = fakeEpoch.Add(time.Duration(h%(5*365*24*3600)) * time.Second)
	e.ATime = model.NanoOf(e.ModTime.Add(time.Duration(h%86400) * time.Second))
	e.CTime = model.NanoOf(e.ModTime)
	e.BirthTime = model.NanoOf(e.ModTime.Add(-time.Duration(h%(30*24*3600)) * time.Second))
}

func (b *FakeBackend) hash(relPath string, salt uint64) uint64 {
	return xxh3.HashStringSeed(relPath, b.seed^salt)
}

// varyCount spreads a count over [n/4, 7n/4] so the tree is lumpy the way real
// ones are — a uniform fan-out hides bugs that only bite on wide directories.
func varyCount(n int, h uint64) int {
	if n == 0 {
		return 0
	}
	return n/4 + int(h%uint64(3*n/2+1))
}

func fakeFrac(h uint64) float64 { return float64(h>>11) / float64(uint64(1)<<53) }

func fakeName(prefix string, i int, ext string) string {
	s := strconv.Itoa(i)
	var sb strings.Builder
	sb.Grow(len(prefix) + 6 + len(ext))
	sb.WriteString(prefix)
	for n := len(s); n < 5; n++ {
		sb.WriteByte('0')
	}
	sb.WriteString(s)
	sb.WriteString(ext)
	return sb.String()
}

// fakeIndex is the i that fakeName(prefix, i, ext) made name from; false
// for a name fakeName never makes.
func fakeIndex(name, prefix, ext string) (int, bool) {
	digits, ok := strings.CutPrefix(name, prefix)
	if ok {
		digits, ok = strings.CutSuffix(digits, ext)
	}
	if !ok {
		return 0, false
	}
	i, err := strconv.Atoi(digits)
	return i, err == nil && i >= 0 && fakeName(prefix, i, ext) == name
}

func joinRel(dir, name string) string {
	if dir == "" {
		return name
	}
	return dir + "/" + name
}

func fakeDelay(ctx context.Context, d time.Duration) error {
	if d <= 0 {
		return nil
	}
	t := time.NewTimer(d)
	defer t.Stop()
	select {
	case <-ctx.Done():
		return ctx.Err()
	case <-t.C:
		return nil
	}
}

// overlayLocked folds the writes in relDir over its generated listing; n is
// relDir's own node. A folder nobody wrote to keeps the generated slice.
func (b *FakeBackend) overlayLocked(relDir string, n fakeMut, entries []model.FileEntry) []model.FileEntry {
	muts := b.over[relDir]
	if len(muts) == 0 {
		return entries
	}
	out := entries[:0]
	for _, e := range entries {
		m, ok := muts[e.Name]
		switch {
		case !ok:
			out = append(out, e)
		case !m.deleted:
			out = append(out, m.at(relDir, e.Name))
		}
	}
	var added []string
	for name, m := range muts {
		if m.deleted {
			continue
		}
		if !n.own {
			if _, generated := b.genEntry(n.gen, name); generated {
				continue // listed above
			}
		}
		added = append(added, name)
	}
	slices.Sort(added)
	for _, name := range added {
		out = append(out, muts[name].at(relDir, name))
	}
	return out
}

func (b *FakeBackend) putLocked(relPath string, m *fakeMut) {
	dir, name := fakeSplit(relPath)
	if b.over[dir] == nil {
		b.over[dir] = make(map[string]*fakeMut)
	}
	b.over[dir][name] = m
}

// file returns the file at relPath, or why it cannot be read as one.
func (b *FakeBackend) file(relPath string) (fakeMut, error) {
	b.mu.RLock()
	n, ok := b.resolveLocked(relPath)
	b.mu.RUnlock()
	switch {
	case !ok:
		return n, fakeMissing(relPath)
	case n.entry.IsDir:
		return n, fmt.Errorf("fake: %s is a folder", relPath)
	}
	return n, nil
}

// reader reads the file n from offset: the bytes a write gave it, or the ones
// the generator makes for the path it stands for.
func (b *FakeBackend) reader(n fakeMut, offset int64) io.ReadCloser {
	if n.own {
		offset = min(max(offset, 0), int64(len(n.data)))
		return io.NopCloser(bytes.NewReader(n.data[offset:]))
	}
	offset = min(max(offset, 0), n.entry.Size)
	return &fakeReader{seed: b.dataSeed(n.gen), off: offset, size: n.entry.Size, have: -1}
}

// Checksum sums the file where it is, as a server does: no bytes cross a
// network, so no bandwidth limit applies.
func (b *FakeBackend) Checksum(ctx context.Context, relPath, algo string) (string, error) {
	return b.checksum(ctx, relPath, algo, 0, -1)
}

// ChecksumRange sums n bytes of relPath from off (model.RegionChecksummer).
// A file that ends before them is io.ErrUnexpectedEOF, as on a local disk.
func (b *FakeBackend) ChecksumRange(ctx context.Context, relPath, algo string, off, n int64) (string, error) {
	return b.checksum(ctx, relPath, algo, off, n)
}

func (b *FakeBackend) checksum(ctx context.Context, relPath, algo string, off, n int64) (string, error) {
	hit, err := b.enter(ctx, FakeChecksum, relPath)
	if err != nil {
		return "", err
	}
	if err := fakeDelay(ctx, b.ckLatency); err != nil {
		return "", err
	}
	h, err := newHash(algo)
	if err != nil {
		return "", err
	}
	node, err := b.file(relPath)
	if err != nil {
		return "", err
	}
	rd := hit.cutReader(b.reader(node, off))
	defer rd.Close()
	if n >= 0 {
		_, err = io.CopyN(h, rd, n)
		if err == io.EOF {
			err = io.ErrUnexpectedEOF
		}
	} else {
		_, err = io.Copy(h, rd)
	}
	if err != nil {
		return "", err
	}
	return hex.EncodeToString(h.Sum(nil)), hit.done(nil)
}

func (b *FakeBackend) ChecksumAlgos(context.Context) ([]string, error) { return localAlgos, nil }

func (b *FakeBackend) Open(ctx context.Context, relPath string) (io.ReadCloser, error) {
	return b.OpenAt(ctx, relPath, 0)
}

func (b *FakeBackend) OpenAt(ctx context.Context, relPath string, offset int64) (io.ReadCloser, error) {
	hit, err := b.enter(ctx, FakeOpen, relPath)
	if err != nil {
		return nil, err
	}
	node, err := b.file(relPath)
	if err != nil {
		return nil, err
	}
	if err := hit.done(nil); err != nil {
		return nil, err
	}
	return LimitReadCloser(ctx, hit.cutReader(b.reader(node, offset))), nil
}

// fakeReader streams deterministic bytes for a synthetic file without ever
// holding the whole body: block N is splitmix64 seeded by (file seed, N).
type fakeReader struct {
	seed  uint64
	off   int64
	size  int64
	block [4096]byte
	have  int64 // block index currently in block[], -1 when empty
}

func (r *fakeReader) Read(p []byte) (int, error) {
	if r.off >= r.size {
		return 0, io.EOF
	}
	n := 0
	for n < len(p) && r.off < r.size {
		idx := r.off / int64(len(r.block))
		if idx != r.have {
			fillBlock(&r.block, r.seed, uint64(idx))
			r.have = idx
		}
		start := int(r.off % int64(len(r.block)))
		c := copy(p[n:], r.block[start:])
		if left := r.size - r.off; int64(c) > left {
			c = int(left)
		}
		n += c
		r.off += int64(c)
	}
	return n, nil
}

func (r *fakeReader) Close() error { return nil }

func fillBlock(buf *[4096]byte, seed, idx uint64) {
	x := seed ^ (idx * 0x9e3779b97f4a7c15)
	for i := 0; i < len(buf); i += 8 {
		x += 0x9e3779b97f4a7c15
		z := x
		z = (z ^ (z >> 30)) * 0xbf58476d1ce4e5b9
		z = (z ^ (z >> 27)) * 0x94d049bb133111eb
		z ^= z >> 31
		binary.LittleEndian.PutUint64(buf[i:], z)
	}
}

// Close does nothing: the tree is generated.
func (b *FakeBackend) Close() error { return nil }

// SetTimes sets the times it is given; a zero time leaves that time as it
// is, and a zero atime is mtime, as on a local disk. The base has no times
// to keep.
func (b *FakeBackend) SetTimes(ctx context.Context, relPath string, mtime, atime, btime time.Time) error {
	hit, err := b.enter(ctx, FakeSetTimes, relPath)
	if err != nil {
		return err
	}
	if relPath == "" {
		return hit.done(nil)
	}
	if atime.IsZero() {
		atime = mtime
	}
	b.mu.Lock()
	n, ok := b.resolveLocked(relPath)
	if ok {
		if !mtime.IsZero() {
			n.entry.ModTime = mtime
		}
		if !atime.IsZero() {
			n.entry.ATime = model.NanoOf(atime)
		}
		if !btime.IsZero() {
			n.entry.BirthTime = model.NanoOf(btime)
		}
		b.putLocked(relPath, &n)
	}
	b.mu.Unlock()
	if !ok {
		return fakeMissing(relPath)
	}
	return hit.done(nil)
}

// CopyFrom writes src to relPath and makes the folders it goes in, as a copy
// to any backend does (the leading-dirs contract). It does not write over a
// folder. A copy that stops half way leaves what it wrote, as a file system
// does.
func (b *FakeBackend) CopyFrom(ctx context.Context, relPath string, src io.Reader, p model.PutParams) error {
	hit, err := b.enter(ctx, FakeCopyFrom, relPath)
	if err != nil {
		return err
	}
	mode := p.Mode.Perm()
	if mode == 0 {
		mode = 0644
	}
	b.mu.Lock()
	err = b.creatableLocked(relPath)
	b.mu.Unlock()
	if err != nil {
		return err
	}
	body, size, rerr := b.take(ctx, src, hit.cut())
	b.mu.Lock()
	err = b.creatableLocked(relPath)
	if err == nil {
		now := time.Now()
		stamp := model.NanoOf(now)
		m := &fakeMut{entry: model.FileEntry{Size: size, Mode: mode, ModTime: now, ATime: stamp, CTime: stamp, BirthTime: stamp}}
		if b.noData {
			m.gen = relPath // bytes the generator makes, as many as were written
		} else {
			m.own, m.data = true, body
		}
		b.putLocked(relPath, m)
	}
	b.mu.Unlock()
	switch {
	case err != nil:
		return err
	case rerr != nil:
		return rerr
	case hit.cutAt(size):
		return hit.fail()
	}
	return hit.done(nil)
}

// creatableLocked makes the folders relPath goes in, and fails when relPath
// is a folder or one of them is a file.
func (b *FakeBackend) creatableLocked(relPath string) error {
	if relPath == "" {
		return errors.New("fake: the base is a folder")
	}
	if err := b.mkdirAllLocked(model.DirOf(relPath), 0755); err != nil {
		return err
	}
	if n, ok := b.resolveLocked(relPath); ok && n.entry.IsDir {
		return fmt.Errorf("fake: %s is a folder", relPath)
	}
	return nil
}

// take reads src to its end or to cut (none when cut < 0): the bytes, how
// many, and the error reading stopped on. With nodata it only counts them.
func (b *FakeBackend) take(ctx context.Context, src io.Reader, cut int64) ([]byte, int64, error) {
	if cut >= 0 {
		src = io.LimitReader(src, cut)
	}
	if b.noData {
		n, err := io.Copy(LimitWriter(ctx, io.Discard), src)
		return nil, n, err
	}
	var sink bytes.Buffer
	n, err := io.Copy(LimitWriter(ctx, &sink), src)
	return sink.Bytes(), n, err
}

// AppendFrom writes the source from offset on at the end of relPath, which
// must hold offset bytes (model.Resumer), as on a local disk.
func (b *FakeBackend) AppendFrom(ctx context.Context, relPath string, src model.RangeOpener, _ model.PutParams, offset int64) error {
	hit, err := b.enter(ctx, FakeAppendFrom, relPath)
	if err != nil {
		return err
	}
	b.mu.RLock()
	_, err = b.appendableLocked(relPath, offset)
	b.mu.RUnlock()
	if err != nil {
		return err
	}
	rd, err := src.OpenAt(ctx, offset)
	if err != nil {
		return err
	}
	defer rd.Close()
	body, size, rerr := b.take(ctx, rd, hit.cut())
	b.mu.Lock()
	err = b.appendLocked(relPath, offset, body, size)
	b.mu.Unlock()
	switch {
	case err != nil:
		return err
	case rerr != nil:
		return rerr
	case hit.cutAt(size):
		return hit.fail()
	}
	return hit.done(nil)
}

// appendableLocked returns the file at relPath when it ends at offset.
func (b *FakeBackend) appendableLocked(relPath string, offset int64) (fakeMut, error) {
	n, ok := b.resolveLocked(relPath)
	switch {
	case !ok:
		return n, appendOffsetErr("fake", relPath, -1, offset)
	case n.entry.IsDir:
		return n, fmt.Errorf("fake: %s is a folder", relPath)
	case n.entry.Size != offset:
		return n, appendOffsetErr("fake", relPath, n.entry.Size, offset)
	}
	return n, nil
}

// appendLocked puts size more bytes at the end of relPath, which must still
// end at offset. A generated file takes its bytes along.
func (b *FakeBackend) appendLocked(relPath string, offset int64, body []byte, size int64) error {
	n, err := b.appendableLocked(relPath, offset)
	if err != nil || size == 0 {
		return err
	}
	if b.noData {
		n.entry.Size += size
	} else {
		data := make([]byte, 0, offset+size)
		if n.own {
			data = append(data, n.data...)
		} else {
			old, err := io.ReadAll(b.reader(n, 0))
			if err != nil {
				return err
			}
			data = append(data, old...)
		}
		n.own, n.data = true, append(data, body...)
		n.entry.Size = int64(len(n.data))
	}
	now := time.Now()
	n.entry.ModTime, n.entry.CTime = now, model.NanoOf(now)
	b.putLocked(relPath, &n)
	return nil
}

// PartSize is the size of relPath's part (model.PartWriter): 0 when there
// is none.
func (b *FakeBackend) PartSize(ctx context.Context, relPath string) (int64, error) {
	hit, err := b.enter(ctx, FakePartSize, relPath)
	if err != nil {
		return 0, err
	}
	if err := fakeDelay(ctx, b.latency); err != nil {
		return 0, err
	}
	part := model.PartPath(relPath)
	b.mu.RLock()
	n, ok := b.resolveLocked(part)
	b.mu.RUnlock()
	switch {
	case !ok:
		return 0, hit.done(nil)
	case n.entry.IsDir:
		return 0, fmt.Errorf("fake: %s is a folder: %w", part, model.ErrPartInTheWay)
	}
	return n.entry.Size, hit.done(nil)
}

// CommitPart gives relPath's part mode and renames it over relPath, which may
// be a file but not a folder.
func (b *FakeBackend) CommitPart(ctx context.Context, relPath string, mode os.FileMode) error {
	hit, err := b.enter(ctx, FakeCommitPart, relPath)
	if err != nil {
		return err
	}
	part := model.PartPath(relPath)
	b.mu.Lock()
	err = func() error {
		if t, ok := b.resolveLocked(relPath); ok && t.entry.IsDir {
			return fmt.Errorf("fake: %s is a folder: %w", relPath, fs.ErrExist)
		}
		n, ok := b.resolveLocked(part)
		if !ok || n.entry.IsDir {
			return fakeMissing(part)
		}
		n.entry.Mode = mode.Perm()
		b.putLocked(part, &n)
		return b.renameLocked(part, relPath, true)
	}()
	b.mu.Unlock()
	if err != nil {
		return err
	}
	return hit.done(nil)
}

// Mkdir makes relPath and the folders above it that are not there, as
// os.MkdirAll does. A folder it makes starts empty.
func (b *FakeBackend) Mkdir(ctx context.Context, relPath string, mode os.FileMode) error {
	hit, err := b.enter(ctx, FakeMkdir, relPath)
	if err != nil {
		return err
	}
	if mode == 0 {
		mode = 0755
	}
	b.mu.Lock()
	err = b.mkdirAllLocked(relPath, mode)
	b.mu.Unlock()
	if err != nil {
		return err
	}
	return hit.done(nil)
}

func (b *FakeBackend) mkdirAllLocked(relPath string, mode os.FileMode) error {
	if n, ok := b.resolveLocked(relPath); ok {
		if n.entry.IsDir {
			return nil
		}
		return fmt.Errorf("fake: %s is a file, not a folder", relPath)
	}
	if err := b.mkdirAllLocked(model.DirOf(relPath), mode); err != nil {
		return err
	}
	now := time.Now()
	stamp := model.NanoOf(now)
	b.putLocked(relPath, &fakeMut{entry: model.FileEntry{
		IsDir: true, Mode: os.ModeDir | mode.Perm(),
		ModTime: now, ATime: stamp, CTime: stamp, BirthTime: stamp,
	}, own: true})
	return nil
}

// Rename moves oldRelPath, and what is in it, to newRelPath, whose folder
// must be there. It refuses a name in use.
func (b *FakeBackend) Rename(ctx context.Context, oldRelPath, newRelPath string) error {
	hit, err := b.enter(ctx, FakeRename, oldRelPath, newRelPath)
	if err != nil {
		return err
	}
	b.mu.Lock()
	err = b.renameLocked(oldRelPath, newRelPath, false)
	b.mu.Unlock()
	if err != nil {
		return err
	}
	return hit.done(nil)
}

// renameLocked moves oldRel to newRel. With replace, a file at newRel is
// replaced (CommitPart).
func (b *FakeBackend) renameLocked(oldRel, newRel string, replace bool) error {
	if oldRel == "" || newRel == "" {
		return errors.New("fake: refusing to rename the base directory")
	}
	n, ok := b.resolveLocked(oldRel)
	if !ok {
		return fakeMissing(oldRel)
	}
	if newRel == oldRel {
		return nil
	}
	if strings.HasPrefix(newRel, oldRel+"/") {
		return fmt.Errorf("fake: cannot move %s into itself", oldRel)
	}
	if t, taken := b.resolveLocked(newRel); taken && (!replace || t.entry.IsDir || n.entry.IsDir) {
		return renameTargetTaken("fake", newRel)
	}
	if p, ok := b.resolveLocked(model.DirOf(newRel)); !ok || !p.entry.IsDir {
		return fakeMissing(model.DirOf(newRel))
	}
	if n.entry.IsDir {
		prefix := oldRel + "/"
		moved := map[string]map[string]*fakeMut{}
		for dir, muts := range b.over {
			if dir == oldRel || strings.HasPrefix(dir, prefix) {
				moved[newRel+dir[len(oldRel):]] = muts
				delete(b.over, dir)
			}
		}
		maps.Copy(b.over, moved)
	}
	b.putLocked(oldRel, &fakeMut{deleted: true})
	b.putLocked(newRel, &n)
	return nil
}

// Remove removes a file, or a folder that holds nothing, as os.Remove does;
// never the base.
func (b *FakeBackend) Remove(ctx context.Context, relPath string) error {
	hit, err := b.enter(ctx, FakeRemove, relPath)
	if err != nil {
		return err
	}
	if relPath == "" {
		return errors.New("fake: refusing to remove the base directory")
	}
	b.mu.Lock()
	err = func() error {
		n, ok := b.resolveLocked(relPath)
		if !ok {
			return fakeMissing(relPath)
		}
		if n.entry.IsDir {
			if len(b.listLocked(relPath, n)) > 0 {
				return fakeNotEmpty(relPath)
			}
			delete(b.over, relPath) // the tombstones of what was in it
		}
		b.putLocked(relPath, &fakeMut{deleted: true})
		return nil
	}()
	b.mu.Unlock()
	if err != nil {
		return err
	}
	return hit.done(nil)
}

// fakeNotEmpty is Remove's error for a folder that holds something. It is
// fs.ErrExist, as the system's own error for it is.
type fakeNotEmpty string

func (e fakeNotEmpty) Error() string        { return "fake: " + string(e) + ": directory not empty" }
func (e fakeNotEmpty) Is(target error) bool { return target == fs.ErrExist }

// RemoveAll removes relPath and all in it, as os.RemoveAll does: a path that
// is not there is no error. Never the base. The writes under a folder go
// with it, so one made again at its path starts empty.
func (b *FakeBackend) RemoveAll(ctx context.Context, relPath string) error {
	hit, err := b.enter(ctx, FakeRemoveAll, relPath)
	if err != nil {
		return err
	}
	if relPath == "" {
		return errors.New("fake: refusing to remove the base directory")
	}
	b.mu.Lock()
	if n, ok := b.resolveLocked(relPath); ok {
		if n.entry.IsDir {
			prefix := relPath + "/"
			for dir := range b.over {
				if dir == relPath || strings.HasPrefix(dir, prefix) {
					delete(b.over, dir)
				}
			}
		}
		b.putLocked(relPath, &fakeMut{deleted: true})
	}
	b.mu.Unlock()
	return hit.done(nil)
}

// FakeOp names a FakeBackend call, for Inject. OpenAt counts as Open and
// ChecksumRange as Checksum: they are those calls from an offset.
type FakeOp string

const (
	FakeList       FakeOp = "List"
	FakeStat       FakeOp = "Stat"
	FakeChecksum   FakeOp = "Checksum"
	FakeOpen       FakeOp = "Open"
	FakeCopyFrom   FakeOp = "CopyFrom"
	FakeAppendFrom FakeOp = "AppendFrom"
	FakeSetTimes   FakeOp = "SetTimes"
	FakeMkdir      FakeOp = "Mkdir"
	FakeRename     FakeOp = "Rename"
	FakeRemove     FakeOp = "Remove"
	FakeRemoveAll  FakeOp = "RemoveAll"
	FakePartSize   FakeOp = "PartSize"
	FakeCommitPart FakeOp = "CommitPart"
)

// FakeFault is what Inject has the fake do to the calls it matches. With only
// Op, Path and Times set, it counts them and does nothing else.
type FakeFault struct {
	// Op is the call; "" matches every call.
	Op FakeOp
	// Path is the path the call is given, either one for Rename: "" for any
	// path, "dir/" for dir and everything in it, else that path. The part
	// file a copy goes into (model.PartPath) matches its file's path too.
	Path string
	// Times is how many matching calls the fault acts on; 0 is every one.
	Times int
	// Delay holds the call this long before it runs. A context that ends
	// first ends the call with the context's error.
	Delay time.Duration
	// Err is the error the call fails with: before it does anything,
	// unless After or Cut says when.
	Err error
	// After: the call does its work, then fails with Err, as when the answer
	// to a request the server carried out is lost. Not with Cut.
	After bool
	// Cut stops a call that moves a file's bytes (Open, CopyFrom,
	// AppendFrom, Checksum) after that many bytes: those are read, written
	// or summed, then the call fails with Err, or io.ErrUnexpectedEOF when
	// Err is nil. A copy cut off leaves the bytes it wrote. A file shorter
	// than Cut is not cut. Other calls ignore it.
	Cut int64
	// Stall: where the call would fail, it stops answering instead, until
	// its context ends, and fails with the context's error.
	Stall bool
}

// FakeInjection is a fault Inject added.
type FakeInjection struct {
	fault FakeFault
	set   *fakeFaults
	hits  int // guarded by set.mu
}

// Hits is how many calls the fault was applied to so far.
func (i *FakeInjection) Hits() int {
	i.set.mu.Lock()
	defer i.set.mu.Unlock()
	return i.hits
}

// Remove takes the fault away.
func (i *FakeInjection) Remove() {
	s := i.set
	s.mu.Lock()
	defer s.mu.Unlock()
	s.list = slices.DeleteFunc(s.list, func(x *FakeInjection) bool { return x == i })
	s.n.Store(int32(len(s.list)))
}

type fakeFaults struct {
	mu   sync.Mutex
	list []*FakeInjection
	n    atomic.Int32 // len(list), read without the lock by every call
}

// Inject adds f after the faults added before it. Each call is checked
// against them in that order, and the first that matches and has tries left
// is applied to it.
func (b *FakeBackend) Inject(f FakeFault) *FakeInjection {
	s := &b.faults
	i := &FakeInjection{fault: f, set: s}
	s.mu.Lock()
	defer s.mu.Unlock()
	s.list = append(s.list, i)
	s.n.Store(int32(len(s.list)))
	return i
}

func (f *FakeFault) matches(op FakeOp, paths []string) bool {
	if f.Op != "" && f.Op != op {
		return false
	}
	if f.Path == "" {
		return true
	}
	dir, subtree := strings.CutSuffix(f.Path, "/")
	for _, p := range paths {
		if subtree && (p == dir || strings.HasPrefix(p, f.Path)) ||
			!subtree && (p == f.Path || p == model.PartPath(f.Path)) {
			return true
		}
	}
	return false
}

// fakeHit is a fault applied to one call.
type fakeHit struct {
	ctx   context.Context
	fault FakeFault
	what  string
}

// enter applies the first fault that matches the call op on paths: it waits
// out the fault's Delay, and fails a call the fault fails before it does
// anything. The hit it returns, nil for none, cuts a data call and fails a
// call that ran (After).
func (b *FakeBackend) enter(ctx context.Context, op FakeOp, paths ...string) (*fakeHit, error) {
	s := &b.faults
	if s.n.Load() == 0 {
		return nil, nil
	}
	var h *fakeHit
	s.mu.Lock()
	for _, i := range s.list {
		if (i.fault.Times == 0 || i.hits < i.fault.Times) && i.fault.matches(op, paths) {
			i.hits++
			h = &fakeHit{ctx: ctx, fault: i.fault, what: string(op) + " " + strings.Join(paths, " ")}
			break
		}
	}
	s.mu.Unlock()
	if h == nil {
		return nil, nil
	}
	if err := fakeDelay(ctx, h.fault.Delay); err != nil {
		return nil, err
	}
	if op != FakeOpen && op != FakeCopyFrom && op != FakeAppendFrom && op != FakeChecksum {
		h.fault.Cut = 0
	}
	if h.fault.Cut <= 0 && !h.fault.After && (h.fault.Err != nil || h.fault.Stall) {
		return nil, h.fail()
	}
	return h, nil
}

// cut is how many bytes the call moves before the fault stops it, -1 for
// all of them.
func (h *fakeHit) cut() int64 {
	if h == nil || h.fault.Cut <= 0 {
		return -1
	}
	return h.fault.Cut
}

// cutAt reports whether a call that moved n bytes was cut.
func (h *fakeHit) cutAt(n int64) bool { return h.cut() >= 0 && n >= h.cut() }

// fail is how the call ends where the fault fails it.
func (h *fakeHit) fail() error {
	if h.fault.Stall {
		<-h.ctx.Done()
		return h.ctx.Err()
	}
	err := h.fault.Err
	if err == nil {
		err = io.ErrUnexpectedEOF
	}
	return fmt.Errorf("fake: %s: %w", h.what, err)
}

// done ends a call that ran: with err when it failed by itself, else as the
// fault says (After).
func (h *fakeHit) done(err error) error {
	if err != nil || h == nil || !h.fault.After || h.fault.Cut > 0 || h.fault.Err == nil && !h.fault.Stall {
		return err
	}
	return h.fail()
}

// cutReader ends rd at the fault's cut.
func (h *fakeHit) cutReader(rd io.ReadCloser) io.ReadCloser {
	if h.cut() < 0 {
		return rd
	}
	return &fakeCutReader{ReadCloser: rd, hit: h, left: h.cut()}
}

type fakeCutReader struct {
	io.ReadCloser
	hit  *fakeHit
	left int64
}

func (r *fakeCutReader) Read(p []byte) (int, error) {
	if r.left <= 0 {
		return 0, r.hit.fail()
	}
	if int64(len(p)) > r.left {
		p = p[:r.left]
	}
	n, err := r.ReadCloser.Read(p)
	r.left -= int64(n)
	return n, err
}
